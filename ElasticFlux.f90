    use fmin_module
    implicit none
    integer,intent(in)::ion_Form
    real(kind(1d0)),intent(in)::aAA,RAA,wA,Q2min
    real(kind(1d0)),intent(in)::xx
    real(kind(1d0)),intent(out)::logQ2oQ02
    real(kind(1d0)),intent(in)::logQ2oQ02min,logQ2oQ02max
